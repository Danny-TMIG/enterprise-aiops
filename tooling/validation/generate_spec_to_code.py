#!/usr/bin/env python3
"""Generate the spec-to-code map for ASF.

Reads:
  - components/{ax,ag,ac}/*/component.json   (per-component identity)
  - catalog/inventories/components.json      (if present, for extra fields)

Writes:
  - docs/architecture/SPEC_TO_CODE.md        (human-readable map)

Idempotent. Read-only with respect to components/. Writes one file.
Run:  python3 tooling/validation/generate_spec_to_code.py
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

def repo_root() -> Path:
    p = Path(__file__).resolve()
    for parent in [p.parent, *p.parents]:
        if (parent / "pyproject.toml").exists():
            return parent
    return p.parent.parent

ROOT = repo_root()

LAYERS = {
    "ax": "Cognition",
    "ag": "Govern",
    "ac": "Compute",
}

FAS_FILES = {
    "Cognition": "Aether_Cognition_Detailed_Functional_Architecture_Specification_v1.0.docx",
    "Govern":    "Aether_Govern_Detailed_Functional_Architecture_Specification_v1.0.docx",
    "Compute":   "Aether_Compute_Detailed_Functional_Architecture_Specification_v1.0.docx",
}

ID_RE = re.compile(r"^(COG|GOV|CMP)-[A-Z]+-\d+$")
SLUG_RE = re.compile(r"^(COG|GOV|CMP)-[A-Z]+-\d+-[a-z0-9-]+$")

# Open decisions that affect each layer, per FAS open-decision tables
OPEN_DECISIONS = {
    "Cognition": ["COG-DEC-002", "COG-DEC-003", "COG-DEC-004", "COG-DEC-005",
                  "COG-DEC-017", "COG-DEC-018"],
    "Govern":    ["GOV-DEC-001", "GOV-DEC-002", "GOV-DEC-003", "GOV-DEC-004",
                  "GOV-DEC-005", "GOV-DEC-007", "GOV-DEC-008", "GOV-DEC-009"],
    "Compute":   ["CMP-DEC-001", "CMP-DEC-002", "CMP-DEC-003", "CMP-DEC-004",
                  "CMP-DEC-005", "CMP-DEC-008", "CMP-DEC-009", "CMP-DEC-010",
                  "CMP-DEC-011", "CMP-DEC-013", "CMP-DEC-014", "CMP-DEC-016"],
}

def read_component_json(d: Path) -> dict:
    f = d / "component.json"
    if not f.exists():
        return {}
    try:
        return json.loads(f.read_text())
    except json.JSONDecodeError:
        return {}

def discover() -> dict:
    """Return {layer_key: [{'id':..., 'slug':..., 'dir':..., 'json':...}]}"""
    out = {}
    for key, layer_name in LAYERS.items():
        layer_dir = ROOT / "components" / key
        entries = []
        if not layer_dir.is_dir():
            out[key] = entries
            continue
        ids = {}
        slugs = {}
        for child in sorted(layer_dir.iterdir()):
            if not child.is_dir():
                continue
            if ID_RE.match(child.name):
                ids[child.name] = child
            elif SLUG_RE.match(child.name):
                base = "-".join(child.name.split("-")[:3])
                slugs[base] = child
        for cid in sorted(ids):
            entries.append({
                "id": cid,
                "dir_bare": ids[cid],
                "dir_slug": slugs.get(cid),
                "json": read_component_json(ids[cid]) or read_component_json(slugs[cid]) if slugs.get(cid) else read_component_json(ids[cid]),
            })
        out[key] = entries
    return out

def layer_summary(entries: list[dict]) -> dict:
    total = len(entries)
    with_slug = sum(1 for e in entries if e["dir_slug"])
    core_v1 = sum(1 for e in entries
                  if str(e["json"].get("release", "")).lower() in ("core v1", "core-v1", "corev1"))
    deferred = sum(1 for e in entries
                   if "defer" in str(e["json"].get("release", "")).lower()
                   or "research" in str(e["json"].get("release", "")).lower()
                   or "validation" in str(e["json"].get("release", "")).lower())
    return {"total": total, "with_slug": with_slug,
            "core_v1": core_v1, "deferred": deferred}

def render(discovered: dict) -> str:
    lines = []
    lines.append("# ASF Spec-to-Code Map\n")
    lines.append("Generated by `tooling/validation/generate_spec_to_code.py`.\n")
    lines.append("Each logical component: its FAS source, its bare-ID directory, its slugged directory, its release scope, and the open decisions that affect it.\n")

    total_all = 0
    for key, layer_name in LAYERS.items():
        entries = discovered[key]
        s = layer_summary(entries)
        total_all += s["total"]
        lines.append(f"\n## {layer_name} (`components/{key}/`)\n")
        lines.append(f"- FAS source: `{FAS_FILES[layer_name]}`\n")
        lines.append(f"- Logical components: {s['total']}\n")
        lines.append(f"- With slugged sibling: {s['with_slug']}\n")
        lines.append(f"- Core v1: {s['core_v1']}\n")
        lines.append(f"- Deferred / validation-gated / research: {s['deferred']}\n")
        lines.append(f"- Open decisions affecting layer: {', '.join(OPEN_DECISIONS[layer_name])}\n")
        lines.append("\n| Component ID | Bare-ID dir | Slugged dir | Release |\n")
        lines.append("|---|---|---|---|\n")
        for e in entries:
            rel = str(e["json"].get("release", "")).strip() or "—"
            bare = e["dir_bare"].name
            slug = e["dir_slug"].name if e["dir_slug"] else "—"
            lines.append(f"| `{e['id']}` | `{bare}` | `{slug}` | {rel} |\n")

    lines.append(f"\n## Totals\n")
    lines.append(f"- Logical components across all layers: **{total_all}**\n")
    lines.append(f"- Expected: 75 (Cognition 21, Govern 24, Compute 30)\n")

    lines.append("\n## Open decisions to close before standing up a runtime\n")
    lines.append("| Decision | Topic |\n")
    lines.append("|---|---|\n")
    for d, topic in [
        ("CMP-DEC-004", "Workload formats (Docker / VM / native)"),
        ("GOV-DEC-002", "Persistent stores"),
        ("GOV-DEC-001 / CMP-DEC-001", "Transport and serialization"),
        ("CMP-DEC-005", "CPU / GPU platforms"),
    ]:
        lines.append(f"| `{d}` | {topic} |\n")

    return "".join(lines)

def main() -> int:
    discovered = discover()
    doc = render(discovered)
    out = ROOT / "docs" / "architecture" / "SPEC_TO_CODE.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(doc)
    total = sum(len(v) for v in discovered.values())
    print(f"wrote {out} ({len(doc)} bytes, {total} components)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
